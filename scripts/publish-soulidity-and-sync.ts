interface ParsedArgs {
  dryRun: boolean
  dryRunTransferOnly: boolean
  resumeCapTransferFromManifest: boolean
  useEnvKey: boolean
  mainnetE2e: boolean
  gasBudget: string | null
  paymentCoinType: string | null
  transferCapsTo: string | null
  privKeyEnv: string
  breakGlassAllowMainnetFreshPublish: boolean
  breakGlassConfirm: string | null
}

export function parseArgs(argv: string[]): ParsedArgs {
  const result: ParsedArgs = {
    dryRun: false,
    dryRunTransferOnly: false,
    resumeCapTransferFromManifest: false,
    useEnvKey: false,
    mainnetE2e: false,
    gasBudget: null,
    paymentCoinType: null,
    transferCapsTo: null,
    privKeyEnv: 'MAINNET_DEPLOYER_PRIV_KEY',
    breakGlassAllowMainnetFreshPublish: false,
    breakGlassConfirm: null,
  }

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i]

    if (arg === '--dry-run') { result.dryRun = true; continue }
    if (arg === '--dry-run-transfer-only') { result.dryRunTransferOnly = true; continue }
    if (arg === '--resume-cap-transfer-from-manifest') { result.resumeCapTransferFromManifest = true; continue }
    if (arg === '--use-env-key') { result.useEnvKey = true; continue }
    if (arg === '--mainnet-e2e') { result.mainnetE2e = true; continue }
    if (arg === '--break-glass-allow-mainnet-fresh-publish') {
      result.breakGlassAllowMainnetFreshPublish = true
      continue
    }

    const valueFor = (flag: string): string | null | undefined => {
      if (arg === flag) {
        const v = argv[i + 1]
        if (!v || v.startsWith('--')) {
          throw new Error(`${flag} requires a value`)
        }
        i += 1
        return v
      }
      if (arg.startsWith(`${flag}=`)) {
        return arg.slice(flag.length + 1)
      }
      return undefined
    }

    let v: string | null | undefined
    if ((v = valueFor('--gas-budget')) !== undefined) { result.gasBudget = v; continue }
    if ((v = valueFor('--payment-coin-type')) !== undefined) { result.paymentCoinType = v; continue }
    if ((v = valueFor('--transfer-caps-to')) !== undefined) { result.transferCapsTo = v; continue }
    if ((v = valueFor('--mainnet-priv-key-env')) !== undefined) { result.privKeyEnv = v ?? result.privKeyEnv; continue }
    if ((v = valueFor('--break-glass-confirm')) !== undefined) { result.breakGlassConfirm = v; continue }
    throw new Error(`Unknown argument: ${arg}`)
  }

  return result
}

// ── Published.toml read/write (preserves other [published.<env>] sections) ──

export function readPublishedTomlSections(path: string): Record<string, string> {
  if (!existsSync(path)) return {}
  const content = readFileSync(path, 'utf8')
  const lines = content.split('\n')
  const sections: Record<string, string[]> = {}
  let current: string | null = null

  for (const line of lines) {
    const m = line.match(/^\[published\.([a-z0-9]+)\]\s*$/)
    if (m) {
      current = m[1]
      sections[current] = [line]
      continue
    }
    if (current) {
      sections[current].push(line)
    }
  }

  const result: Record<string, string> = {}
  for (const env of Object.keys(sections)) {
    while (sections[env].length > 1 && sections[env][sections[env].length - 1].trim() === '') {
      sections[env].pop()
    }
    result[env] = sections[env].join('\n')
  }
  return result
}

function formatPublishedSection(env: string, s: PublishedSection): string {
  return [
    `[published.${env}]`,
    `chain-id = "${s.chainId}"`,
    `published-at = "${s.packageId}"`,
    `original-id = "${s.packageId}"`,
    `version = ${s.version}`,
    `toolchain-version = "${s.toolchainVersion}"`,
    `build-config = { flavor = "sui", edition = "2024" }`,
    `upgrade-capability = "${s.upgradeCapId}"`,
  ].join('\n')
}

export function writePublishedTomlSection(path: string, env: string, section: PublishedSection) {
  const sections = readPublishedTomlSections(path)
  sections[env] = formatPublishedSection(env, section)
  const ordered = Object.keys(sections).sort().map((k) => sections[k])
  const content = `${PUBLISHED_TOML_HEADER}\n${ordered.join('\n\n')}\n`
  atomicWriteText(path, content)
}

function copyPublishedTomlSectionFromTemp(tempPath: string, sourcePath: string, env: string) {
  const tempSections = readPublishedTomlSections(tempPath)
  const tempSectionText = tempSections[env]
  if (!tempSectionText) {
    throw new Error(`Temp Published.toml has no [published.${env}] section`)
  }
  const sourceSections = readPublishedTomlSections(sourcePath)
  sourceSections[env] = tempSectionText
  const ordered = Object.keys(sourceSections).sort().map((k) => sourceSections[k])
  const content = `${PUBLISHED_TOML_HEADER}\n${ordered.join('\n\n')}\n`
  atomicWriteText(sourcePath, content)
}

