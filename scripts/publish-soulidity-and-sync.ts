function resolveSuiBin() {
  const candidates = [
    process.env.SUI_BIN,
    join(homedir(), '.local', 'bin', 'sui'),
    'sui',
  ].filter((value): value is string => Boolean(value))

  for (const candidate of candidates) {
    if (candidate === 'sui' || existsSync(candidate)) {
      return candidate
    }
  }

  return 'sui'
}

