function readJsonFile<T>(path: string): T {
  return JSON.parse(readFileSync(path, 'utf8')) as T
}

function writeJsonFile(path: string, value: unknown) {
  atomicWriteJson(path, value)
}

export function readReleaseAttempt(path = releaseAttemptPath): ReleaseAttempt | null {
  if (!existsSync(path)) {
    throw new Error(
      `Release-attempt journal is missing at ${path}; refusing any signed release operation.`,
    )
  }
  const parsed = readJsonFile<unknown>(path)
  if (parsed === null) return null
  if (!parsed || typeof parsed !== 'object') {
    throw new Error(`Release-attempt journal ${path} must contain null or an object.`)
  }
  const attempt = parsed as Partial<ReleaseAttempt>
  if (
    (attempt.operation !== 'fresh-publish' && attempt.operation !== 'cap-transfer')
    || (attempt.network !== 'mainnet' && attempt.network !== 'testnet')
    || !['signing', 'submitted', 'verified'].includes(attempt.status ?? '')
    || typeof attempt.startedAt !== 'string'
    || typeof attempt.deployerAddr !== 'string'
  ) {
    throw new Error(`Release-attempt journal ${path} is malformed; refusing to sign.`)
  }
  return attempt as ReleaseAttempt
}

export function assertNoPendingReleaseAttempt(path = releaseAttemptPath): void {
  const attempt = readReleaseAttempt(path)
  if (!attempt) return
  throw new Error(
    `A ${attempt.operation} release attempt is still ${attempt.status}`
      + `${attempt.digest ? ` at digest ${attempt.digest}` : ''}. `
      + 'DO NOT RETRY or clear the journal until the signer history and all affected '
      + 'on-chain objects have been reconciled.',
  )
}

function writeReleaseAttempt(attempt: ReleaseAttempt | null): void {
  atomicWriteJson(releaseAttemptPath, attempt)
}

function beginReleaseAttempt(
  attempt: Omit<ReleaseAttempt, 'status' | 'startedAt'>,
): ReleaseAttempt {
  assertNoPendingReleaseAttempt()
  const record: ReleaseAttempt = {
    ...attempt,
    status: 'signing',
    startedAt: new Date().toISOString(),
  }
  writeReleaseAttempt(record)
  return record
}

function updateReleaseAttempt(
  attempt: ReleaseAttempt,
  patch: Partial<ReleaseAttempt>,
): ReleaseAttempt {
  const current = readReleaseAttempt()
  if (!current || current.startedAt !== attempt.startedAt) {
    throw new Error(
      'Release-attempt journal changed during the chain operation; refusing to overwrite it.',
    )
  }
  const updated = { ...current, ...patch }
  writeReleaseAttempt(updated)
  return updated
}

function clearReleaseAttempt(attempt: ReleaseAttempt): void {
  const current = readReleaseAttempt()
  if (!current || current.startedAt !== attempt.startedAt) {
    throw new Error(
      'Release-attempt journal changed before completion; refusing to clear it.',
    )
  }
  writeReleaseAttempt(null)
}

